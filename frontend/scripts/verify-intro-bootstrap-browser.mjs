import assert from "node:assert/strict";
import { pathToFileURL } from "node:url";
const base = process.env.TEST_BASE_URL || "http://127.0.0.1:3100";
assert.ok(["localhost", "127.0.0.1"].includes(new URL(base).hostname));
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE || "C:/Users/crist/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs").href);
const browser = await chromium.launch({ headless: true, executablePath: process.env.BROWSER_EXECUTABLE || "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe", args: ["--mute-audio", "--autoplay-policy=no-user-gesture-required", "--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
let checks = 0;
function check(condition, label) { assert.ok(condition, label); checks++; console.log(`PASS ${label}`); }
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const page = await context.newPage(), errors = [], scenes = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (new URL(request.url()).pathname === "/intro-scene/index.html") scenes.push(request.url()); });
  await context.route("**/api/**", route => route.abort());
  let release;
  const hydrationGate = new Promise(resolve => { release = resolve; });
  await context.route("**/_next/static/chunks/*.js", async route => { await hydrationGate; await route.continue(); });
  await page.goto(base + "/?intro=preview", { waitUntil: "commit" });
  await page.waitForFunction(() => window.__algolabIntroBoot?.ready, { timeout: 45000 });
  const scene = page.frames().find(frame => frame.url().includes("/intro-scene/index.html"));
  check(Boolean(scene), "the original iframe is prepared before Next.js hydration");
  check(await page.evaluate(() => {
    const layer = document.querySelector('[data-intro-scene-layer]').getBoundingClientRect();
    return getComputedStyle(document.documentElement).overflowY === 'hidden' && document.documentElement.clientWidth === innerWidth && Math.abs(layer.right - innerWidth) < 1;
  }), "pre-hydration intro already suppresses the native scrollbar and covers the viewport");
  check(await page.locator("audio[data-intro-soundtrack]").count() === 0, "preparation does not play unsynchronized sound before controls exist");
  const identity = await scene.evaluate(() => window.__continuityDiagnostics().instanceId);
  check(Boolean(identity), "the real 3D protagonist is already loaded");
  release();
  await page.waitForFunction(() => document.querySelector("audio[data-intro-soundtrack]")?.currentTime > .05, { timeout: 45000 });
  check(scenes.length === 1, "React adopts the iframe without requesting or loading it again");
  check(await scene.evaluate(() => window.__continuityDiagnostics().instanceId) === identity, "hydration preserves the same robot instance");
  check(await page.evaluate(() => !window.__algolabIntroBoot), "the bootstrap releases listeners and document observer after handoff");
  const fonts = await page.evaluate(() => performance.getEntriesByType("resource").filter(x => x.name.endsWith(".woff2")).map(x => x.name));
  check(fonts.length === 1 && fonts[0].includes("nunito"), "only the font actually used on the landing is downloaded");
  await page.getByRole("button", { name: "Silenciar sonido" }).tap();
  check(await page.locator("audio[data-intro-soundtrack]").evaluate(a => a.muted && !a.paused), "mute remains independent of playback");
  await page.getByRole("button", { name: "Omitir", exact: true }).tap();
  await scene.waitForFunction(() => window.__continuityDiagnostics().landed);
  check(await scene.evaluate(() => window.__continuityDiagnostics().instanceId) === identity, "skip hands the same protagonist to the landing");
  await page.waitForFunction(() => getComputedStyle(document.documentElement).overflowY !== 'hidden' && !document.querySelector('[data-intro-scene-layer]')?.hasAttribute('data-playing'));
  check(true, "ending the intro restores the normal document scrollbar and scrolling");
  check(errors.length === 0, `no hydration or runtime errors: ${errors.join("; ")}`);
  await context.close();
  const changed = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const changedPage = await changed.newPage();
  let continueHydration;
  const changedGate = new Promise(resolve => { continueHydration = resolve; });
  await changed.route("**/api/**", route => route.abort());
  await changed.route("**/_next/static/chunks/*.js", async route => { await changedGate; await route.continue(); });
  await changedPage.goto(base, { waitUntil: "commit" });
  await changedPage.waitForFunction(() => window.__algolabIntroBoot?.ready, { timeout: 45000 });
  await changedPage.evaluate(() => localStorage.setItem("algolab:intro:preference", "never"));
  continueHydration();
  await changedPage.waitForFunction(() => !window.__algolabIntroBoot && !document.querySelector("iframe[data-intro-scene]")?.hasAttribute("src"));
  check(await changedPage.locator("audio[data-intro-soundtrack]").count() === 0, "a preference changed before hydration cancels the prepared intro");
  check(await changedPage.locator("iframe[data-intro-scene]").evaluate(f => !f.parentElement.hasAttribute("data-enabled") && !f.parentElement.hasAttribute("data-playing")), "cancellation removes the early overlay and unloads its GPU context");
  await changed.close();
  console.log(JSON.stringify({ checks }));
} finally { await browser.close(); }
